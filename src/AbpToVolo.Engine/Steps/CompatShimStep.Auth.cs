    private static string SimpleStringCipherShim(string ns) => $$"""
        using System;
        using System.Security.Cryptography;
        using System.Text;

        namespace {{ns}};

        /// <summary>
        /// Generated by AbpToVolo: Boilerplate's SimpleStringCipher (same algorithm and defaults: AES-256-CBC, key from
        /// PBKDF2/SHA1), so values encrypted by the source (e.g. EncryptedAccessToken / enc_auth_token) still decrypt.
        /// </summary>
        public class SimpleStringCipher
        {
            public const int DefaultKeysize = 256;

            public static SimpleStringCipher Instance { get; } = new();

            public static string DefaultPassPhrase { get; set; } = "gsKnGZ041HLL4IM8";

            public static byte[] DefaultInitVectorBytes { get; set; } = Encoding.ASCII.GetBytes("jkE49230Tf093b42");

            public static byte[] DefaultSalt { get; set; } = Encoding.ASCII.GetBytes("hgt!16kl");

            public string? Encrypt(string? plainText, string? passPhrase = null, byte[]? salt = null, int? keySize = null, byte[]? initVectorBytes = null)
            {
                if (plainText is null) return null;
                using var aes = Create(passPhrase, salt, keySize);
                var bytes = aes.EncryptCbc(Encoding.UTF8.GetBytes(plainText), initVectorBytes ?? DefaultInitVectorBytes, PaddingMode.PKCS7);
                return Convert.ToBase64String(bytes);
            }

            public string? Decrypt(string? cipherText, string? passPhrase = null, byte[]? salt = null, int? keySize = null, byte[]? initVectorBytes = null)
            {
                if (string.IsNullOrEmpty(cipherText)) return null;
                using var aes = Create(passPhrase, salt, keySize);
                var bytes = aes.DecryptCbc(Convert.FromBase64String(cipherText), initVectorBytes ?? DefaultInitVectorBytes, PaddingMode.PKCS7);
                return Encoding.UTF8.GetString(bytes);
            }

            private static Aes Create(string? passPhrase, byte[]? salt, int? keySize)
            {
                var aes = Aes.Create();
                aes.Mode = CipherMode.CBC;
                aes.Key = Rfc2898DeriveBytes.Pbkdf2(passPhrase ?? DefaultPassPhrase, salt ?? DefaultSalt, 1000, HashAlgorithmName.SHA1, (keySize ?? DefaultKeysize) / 8);
                return aes;
            }
        }

        """;

