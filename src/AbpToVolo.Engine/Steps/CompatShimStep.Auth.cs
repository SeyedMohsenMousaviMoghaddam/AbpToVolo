    /// <summary>Writes a shim even when the converted code does not use it (generated code of other steps needs it).</summary>
    public static void EnsureShim(MigrationContext context, string fileName)
    {
        var shim = Shims.First(s => s.FileName == fileName);
        if (Target(context, shim.Layer) is not var (project, ns)) return;
        var path = Path.Combine(project.Directory, ShimFolder, shim.FileName);
        if (!File.Exists(path)) FileSystem.WriteText(path, shim.Code(ns));
    }

