    private static string LogInManagerShim(string ns) => $$"""
        using System;
        using System.Linq;
        using System.Security.Claims;
        using System.Threading.Tasks;
        using Microsoft.AspNetCore.Identity;
        using Microsoft.Extensions.Localization;
        using Volo.Abp;
        using Volo.Abp.Data;
        using Volo.Abp.DependencyInjection;
        using Volo.Abp.Identity;
        using Volo.Abp.Localization;
        using Volo.Abp.MultiTenancy;
        using Volo.Abp.Security.Claims;
        using Volo.Abp.TenantManagement;
        using IdentityUser = Volo.Abp.Identity.IdentityUser;

        namespace {{ns}};

        /// <summary>Generated by AbpToVolo: Boilerplate's login result types.</summary>
        public enum AbpLoginResultType : byte
        {
            Success = 1,
            InvalidUserNameOrEmailAddress,
            InvalidPassword,
            UserIsNotActive,
            InvalidTenancyName,
            TenantIsNotActive,
            UserEmailIsNotConfirmed,
            UnknownExternalLogin,
            LockedOut,
            UserPhoneNumberIsNotConfirmed,
            FailedForOtherReason
        }

        public class AbpLoginResult<TTenant, TUser>
            where TTenant : class
            where TUser : class
        {
            public AbpLoginResultType Result { get; private set; }

            public string? FailReason { get; private set; }

            public TTenant? Tenant { get; private set; }

            public TUser? User { get; private set; }

            public ClaimsIdentity? Identity { get; private set; }

            public AbpLoginResult(AbpLoginResultType result, TTenant? tenant = null, TUser? user = null)
            {
                Result = result;
                Tenant = tenant;
                User = user;
            }

            public AbpLoginResult(TTenant? tenant, TUser user, ClaimsIdentity identity)
                : this(AbpLoginResultType.Success, tenant)
            {
                User = user;
                Identity = identity;
            }

            public void SetFailReason(string reason) => FailReason = reason;
        }

        /// <summary>
        /// Generated by AbpToVolo: Boilerplate's LogInManager.LoginAsync on top of IdentityUserManager (same password hashes:
        /// ASP.NET Core Identity), with the same results and lockout handling. The identity has the claims of the ABP.io
        /// claims principal factory (plus ClaimTypes.NameIdentifier, which the Boilerplate token code reads).
        /// </summary>
        public class LogInManager : ITransientDependency
        {
            protected IdentityUserManager UserManager { get; }

            protected ITenantRepository TenantRepository { get; }

            protected ICurrentTenant CurrentTenant { get; }

            protected IUserClaimsPrincipalFactory<IdentityUser> ClaimsPrincipalFactory { get; }

            public LogInManager(IdentityUserManager userManager, ITenantRepository tenantRepository, ICurrentTenant currentTenant,
                IUserClaimsPrincipalFactory<IdentityUser> claimsPrincipalFactory)
            {
                UserManager = userManager;
                TenantRepository = tenantRepository;
                CurrentTenant = currentTenant;
                ClaimsPrincipalFactory = claimsPrincipalFactory;
            }

            public virtual async Task<AbpLoginResult<Tenant, IdentityUser>> LoginAsync(string userNameOrEmailAddress, string plainPassword, string? tenancyName = null,
                bool shouldLockout = true)
            {
                Tenant? tenant = null;
                if (!string.IsNullOrWhiteSpace(tenancyName))
                {
                    tenant = await FindTenantAsync(tenancyName);
                    if (tenant is null) return new(AbpLoginResultType.InvalidTenancyName);
                    if (tenant.HasProperty("IsActive") && !tenant.GetProperty<bool>("IsActive")) return new(AbpLoginResultType.TenantIsNotActive, tenant);
                }

                using (CurrentTenant.Change(tenant?.Id))
                {
                    var user = await UserManager.FindByNameAsync(userNameOrEmailAddress) ?? await UserManager.FindByEmailAsync(userNameOrEmailAddress);
                    if (user is null) return new(AbpLoginResultType.InvalidUserNameOrEmailAddress, tenant);
                    if (await UserManager.IsLockedOutAsync(user)) return new(AbpLoginResultType.LockedOut, tenant, user);

                    if (!await UserManager.CheckPasswordAsync(user, plainPassword))
                    {
                        if (shouldLockout && await UserManager.GetLockoutEnabledAsync(user)) await UserManager.AccessFailedAsync(user);
                        return new(AbpLoginResultType.InvalidPassword, tenant, user);
                    }

                    await UserManager.ResetAccessFailedCountAsync(user);
                    if (!user.IsActive) return new(AbpLoginResultType.UserIsNotActive, tenant, user);

                    var principal = await ClaimsPrincipalFactory.CreateAsync(user);
                    var identity = (ClaimsIdentity)principal.Identity!;
                    if (!identity.HasClaim(c => c.Type == ClaimTypes.NameIdentifier)) identity.AddClaim(new Claim(ClaimTypes.NameIdentifier, user.Id.ToString()));
                    return new(tenant, user, identity);
                }
            }

            /// <summary>By the Boilerplate tenancy name (kept as the TenancyName extension), else by name.</summary>
            protected virtual async Task<Tenant?> FindTenantAsync(string tenancyName)
            {
                var tenants = await TenantRepository.GetListAsync();
                return tenants.FirstOrDefault(t => string.Equals(t.GetProperty<string>("TenancyName"), tenancyName, StringComparison.OrdinalIgnoreCase)) ??
                       tenants.FirstOrDefault(t => string.Equals(t.Name, tenancyName, StringComparison.OrdinalIgnoreCase));
            }
        }

        /// <summary>
        /// Generated by AbpToVolo: ABP.io puts the user id in AbpClaimTypes.UserId ("sub"), Boilerplate in ClaimTypes.NameIdentifier,
        /// which the Boilerplate token code reads (CreateJwtClaims). Every principal of the claims principal factory
        /// (SignInManager.CreateUserPrincipalAsync, LogInManager...) gets both.
        /// </summary>
        public class BoilerplateClaimsPrincipalContributor : IAbpClaimsPrincipalContributor, ITransientDependency
        {
            public virtual Task ContributeAsync(AbpClaimsPrincipalContributorContext context)
            {
                var identity = context.ClaimsPrincipal.Identities.FirstOrDefault();
                if (identity is null || identity.HasClaim(c => c.Type == ClaimTypes.NameIdentifier)) return Task.CompletedTask;
                if (identity.FindFirst(AbpClaimTypes.UserId)?.Value is { Length: > 0 } userId) identity.AddClaim(new Claim(ClaimTypes.NameIdentifier, userId));
                return Task.CompletedTask;
            }
        }

        /// <summary>Generated by AbpToVolo: Boilerplate's messages for failed logins (keys of the default localization resource).</summary>
        public class AbpLoginResultTypeHelper : ITransientDependency
        {
            private readonly IStringLocalizer? _localizer;

            public AbpLoginResultTypeHelper(IStringLocalizerFactory localizerFactory)
            {
                _localizer = localizerFactory.CreateDefaultOrNull();
            }

            private string L(string key, params object?[] args) => _localizer is null ? string.Format(key, args) : _localizer[key, args!].Value;

            public virtual Exception CreateExceptionForFailedLoginAttempt(AbpLoginResultType result, string usernameOrEmailAddress, string? tenancyName) =>
                result == AbpLoginResultType.Success
                    ? new Exception("Don't call this method with a success result!")
                    : new UserFriendlyException(L("LoginFailed"), CreateLocalizedMessageForFailedLoginAttempt(result, usernameOrEmailAddress, tenancyName));

            public virtual string CreateLocalizedMessageForFailedLoginAttempt(AbpLoginResultType result, string usernameOrEmailAddress, string? tenancyName) =>
                result switch
                {
                    AbpLoginResultType.InvalidUserNameOrEmailAddress or AbpLoginResultType.InvalidPassword => L("InvalidUserNameOrPassword"),
                    AbpLoginResultType.InvalidTenancyName => L("ThereIsNoTenantDefinedWithName{0}", tenancyName),
                    AbpLoginResultType.TenantIsNotActive => L("TenantIsNotActive", tenancyName),
                    AbpLoginResultType.UserIsNotActive => L("UserIsNotActiveAndCanNotLogin", usernameOrEmailAddress),
                    AbpLoginResultType.UserEmailIsNotConfirmed => L("UserEmailIsNotConfirmedAndCanNotLogin"),
                    AbpLoginResultType.LockedOut => L("UserLockedOutMessage"),
                    _ => L("LoginFailed")
                };
        }

        """;
