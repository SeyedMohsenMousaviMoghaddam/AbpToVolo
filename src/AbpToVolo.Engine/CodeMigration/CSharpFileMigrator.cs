using AbpToVolo.CodeMigration.Rewriters;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace AbpToVolo.CodeMigration;

public sealed record CSharpMigrationResult(string Code, bool Changed, FileMigrationContext Context);

/// <summary>Runs the rewriter pipeline over one C# source file.</summary>
public static class CSharpFileMigrator
{
    private static readonly CSharpParseOptions ParseOptions = new(LanguageVersion.Preview, DocumentationMode.None);

    /// <summary>
    /// Order matters: rewriters that recognise Boilerplate names (AbpModule, AsyncCrudAppService, IocManager...)
    /// run before <see cref="TypeNameRewriter"/> renames them; <see cref="UsingsRewriter"/> runs last so it can add
    /// every namespace the previous rewriters asked for.
    /// </summary>
    private static readonly Func<FileMigrationContext, CSharpSyntaxRewriter>[] Pipeline =
    [
        c => new ModuleClassRewriter(c),
        c => new CrudAppServiceRewriter(c),
        c => new DefinitionProviderRewriter(c),
        c => new DbContextRewriter(c),
        c => new StartupRewriter(c),
        c => new ActiveTransactionRewriter(c),
        c => new RepositoryCallRewriter(c),
        c => new ServiceMembersRewriter(c),
        c => new LocalizationRewriter(c),
        c => new ExceptionRewriter(c),
        c => new JwtClaimsRewriter(c),
        c => new AttributeRewriter(c),
        c => new TypeNameRewriter(c),
        c => new UsingsRewriter(c),
    ];

    public static bool IsGenerated(string code) =>
        code.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase);

    public static CSharpMigrationResult Migrate(string code, FileMigrationContext context)
    {
        var tree = CSharpSyntaxTree.ParseText(code, ParseOptions, context.FilePath);
        SyntaxNode root = tree.GetRoot();

        new ZeroDetector(context).Visit(root);

        foreach (var factory in Pipeline)
        {
            root = factory(context).Visit(root) ?? root;
            // Re-parse so that the next rewriter sees a consistent tree with parents and positions.
            root = CSharpSyntaxTree.ParseText(root.ToFullString(), ParseOptions, context.FilePath).GetRoot();
        }

        var result = root.ToFullString();
        return new CSharpMigrationResult(result, !string.Equals(result, code, StringComparison.Ordinal), context);
    }
}
